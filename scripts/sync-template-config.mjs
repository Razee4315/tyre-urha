function replaceInTextFiles(dir, from, to) {
  if (!fs.existsSync(dir) || from === to) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      replaceInTextFiles(fullPath, from, to);
      continue;
    }
    const text = fs.readFileSync(fullPath, "utf8");
    fs.writeFileSync(fullPath, text.split(from).join(to));
  }
}

function detectAndroidPackage(dir) {
  if (!fs.existsSync(dir)) return null;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      const nested = detectAndroidPackage(fullPath);
      if (nested) return nested;
      continue;
    }
    if (!entry.name.endsWith(".kt")) continue;
    const fileText = fs.readFileSync(fullPath, "utf8");
    const match = fileText.match(/^package\s+([^\s]+)$/m);
    if (match) return match[1];
  }
  return null;
}

function detectAndroidLibraryName(dir) {
  if (!fs.existsSync(dir)) return null;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      const nested = detectAndroidLibraryName(fullPath);
      if (nested) return nested;
      continue;
    }
    if (!entry.name.endsWith(".kt")) continue;
    const fileText = fs.readFileSync(fullPath, "utf8");
    const match = fileText.match(/System\.loadLibrary\("([^"]+)"\)/);
    if (match) return match[1];
  }
  return null;
}

function findFile(dir, filename) {
  if (!fs.existsSync(dir)) return null;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      const nested = findFile(fullPath, filename);
      if (nested) return nested;
      continue;
    }
    if (entry.name === filename) return fullPath;
  }
  return null;
}

function syncPackageFolder(baseDir, fromPackage, toPackage) {
  if (!fs.existsSync(baseDir) || fromPackage === toPackage) return;

  const fromPath = path.join(baseDir, ...fromPackage.split("."));
  const toPath = path.join(baseDir, ...toPackage.split("."));

  if (!fs.existsSync(fromPath)) return;

  fs.mkdirSync(path.dirname(toPath), { recursive: true });

  if (fs.existsSync(toPath)) {
    moveChildren(fromPath, toPath);
    fs.rmSync(fromPath, { recursive: true, force: true });
  } else {
    fs.renameSync(fromPath, toPath);
  }

  removeEmptyParents(path.dirname(fromPath), baseDir);
}

function moveChildren(fromDir, toDir) {
  fs.mkdirSync(toDir, { recursive: true });
  for (const entry of fs.readdirSync(fromDir, { withFileTypes: true })) {
    const fromPath = path.join(fromDir, entry.name);
    const toPath = path.join(toDir, entry.name);
    if (entry.isDirectory()) {
      if (fs.existsSync(toPath)) {
        moveChildren(fromPath, toPath);
        fs.rmSync(fromPath, { recursive: true, force: true });
      } else {
        fs.renameSync(fromPath, toPath);
      }
      continue;
    }
    if (fs.existsSync(toPath)) {
      fs.rmSync(toPath, { force: true });
    }
    fs.renameSync(fromPath, toPath);
  }
}

function removeEmptyParents(startDir, stopDir) {
  let current = startDir;
  while (current.startsWith(stopDir) && current !== stopDir) {
    if (fs.existsSync(current) && fs.readdirSync(current).length === 0) {
      fs.rmdirSync(current);
      current = path.dirname(current);
      continue;
    }
    break;
  }
}

function semverToVersionCode(version) {
  const [major = 0, minor = 0, patch = 0] = version.split(".").map(Number);
  return major * 10000 + minor * 100 + patch;
}

function escapeXml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

// Android string resources require apostrophes and double quotes to be
// escaped with a backslash even after XML decoding, otherwise aapt2 fails
// the resource compile with "Invalid unicode escape sequence in string".
function escapeAndroidString(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll("\\", "\\\\")
    .replaceAll("'", "\\'")
    .replaceAll('"', '\\"');
}
